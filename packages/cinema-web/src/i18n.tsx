export function resolveLocale(language: string | null | undefined): Locale {
  return language?.toLowerCase().startsWith("zh") ? "zh-CN" : "en-US"
}

export function readLocalePreference(): Locale {
  try {
    const stored = window.localStorage.getItem(CINEMA_LOCALE_STORAGE_KEY)
    if (stored === "zh-CN" || stored === "en-US") return stored
  } catch {
    // Fall back to the system language when storage is unavailable.
  }

  return resolveLocale(typeof navigator === "undefined" ? undefined : navigator.language)
}

export function translate(locale: Locale, key: TranslationKey, params: TranslationParams = {}): string {
  const template = (locale === "zh-CN" ? zhCN : enUS)[key] ?? enUS[key] ?? key
  return template.replace(/\{([^}]+)\}/g, (match, name: string) => (
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match
  ))
}

type I18nContextValue = {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: (key: TranslationKey, params?: TranslationParams) => string
}

const I18nContext = createContext<I18nContextValue | null>(null)

export function I18nProvider({ children, locale: localeOverride }: { children: ReactNode; locale?: Locale }) {
  const [locale, setLocaleState] = useState<Locale>(() => localeOverride ?? readLocalePreference())

  useEffect(() => {
    if (localeOverride) setLocaleState(localeOverride)
  }, [localeOverride])

  useEffect(() => {
    document.documentElement.lang = locale

    if (localeOverride) return
    try {
      window.localStorage.setItem(CINEMA_LOCALE_STORAGE_KEY, locale)
    } catch {
      // Language selection still applies for the current page when storage is unavailable.
    }
  }, [locale, localeOverride])

  const value = useMemo<I18nContextValue>(() => ({
    locale,
    setLocale: setLocaleState,
    t: (key, params) => translate(locale, key, params),
  }), [locale])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nContextValue {
  const context = useContext(I18nContext)
  if (!context) throw new Error("useI18n must be used inside I18nProvider")
  return context
}
