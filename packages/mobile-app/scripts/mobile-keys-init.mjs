import {
  createCipheriv,
  createHash,
  pbkdf2Sync,
  randomBytes,
  X509Certificate,
} from "node:crypto"
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs"
import path from "node:path"
import { spawnSync } from "node:child_process"
import { fileURLToPath } from "node:url"

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const repoRoot = path.resolve(packageRoot, "..", "..")
const privateRoot = path.join(repoRoot, ".anybox-mobile-keys")
const androidKeyDirectory = path.join(privateRoot, "android")
const otaKeyDirectory = path.join(privateRoot, "ota")
const temporaryCertificateDirectory = path.join(privateRoot, "certificate")
const keystorePath = path.join(androidKeyDirectory, "anybox-mobile-release.jks")
const otaPrivateKeyPath = path.join(otaKeyDirectory, "private-key.pem")
const otaPublicKeyPath = path.join(otaKeyDirectory, "public-key.pem")
const generatedCertificatePath = path.join(temporaryCertificateDirectory, "certificate.pem")
const committedCertificatePath = path.join(packageRoot, "credentials", "ota-certificate.pem")
const committedAndroidFingerprintPath = path.join(
  packageRoot,
  "credentials",
  "android-release-certificate.sha256",
)
const envPath = path.join(repoRoot, ".env.mobile-signing.local")
const androidAlias = "anybox-mobile"
const backupFileName = "anybox-mobile-production-keys-v1.enc.json"
const isWindows = process.platform === "win32"

function usage() {
  return [
    "Initialize the Anybox Android production signing keys.",
    "",
    "Required:",
    "  --primary-backup <absolute-directory>",
    "    or ANYBOX_MOBILE_BACKUP_DIR_PRIMARY",
    "  --secondary-backup <absolute-directory>",
    "    or ANYBOX_MOBILE_BACKUP_DIR_SECONDARY",
    "  ANYBOX_MOBILE_BACKUP_PASSPHRASE (at least 16 characters)",
    "",
    "The two backup directories must be distinct and outside this Git repository.",
    "No existing key, certificate, env file, or backup is ever overwritten.",
  ].join("\n")
}

function parseArgs(argv) {
  const result = {
    help: false,
    primaryBackup: process.env.ANYBOX_MOBILE_BACKUP_DIR_PRIMARY ?? "",
    secondaryBackup: process.env.ANYBOX_MOBILE_BACKUP_DIR_SECONDARY ?? "",
  }
  for (let index = 0; index < argv.length; index += 1) {
    const value = argv[index]
    if (value === "--help" || value === "-h") result.help = true
    else if (value === "--primary-backup") {
      result.primaryBackup = argv[index + 1] ?? ""
      index += 1
    } else if (value === "--secondary-backup") {
      result.secondaryBackup = argv[index + 1] ?? ""
      index += 1
    } else if (value !== "--") {
      throw new Error(`Unknown option: ${value}`)
    }
  }
  return result
}

function isInside(parent, candidate) {
  const relative = path.relative(parent, candidate)
  return relative === "" || (!relative.startsWith("..") && !path.isAbsolute(relative))
}

function requireFreshPath(filePath, label) {
  if (existsSync(filePath)) throw new Error(`${label} already exists; refusing to overwrite it: ${filePath}`)
}

function randomPassword() {
  return randomBytes(24).toString("base64url")
}

function run(command, args, options = {}) {
  const result = spawnSync(command, args, {
    cwd: options.cwd ?? packageRoot,
    encoding: "utf8",
    env: options.env ?? process.env,
    shell: options.shell ?? (isWindows && /\.(?:bat|cmd)$/i.test(command)),
    stdio: options.capture ? "pipe" : "inherit",
    windowsHide: true,
  })
  if (result.status !== 0) {
    throw new Error(`${path.basename(command)} failed; no existing key material was overwritten.`)
  }
  return `${result.stdout ?? ""}${result.stderr ?? ""}`.trim()
}

function createEncryptedBackup(payload, passphrase) {
  const salt = randomBytes(32)
  const iv = randomBytes(12)
  const key = pbkdf2Sync(passphrase, salt, 600_000, 32, "sha512")
  const cipher = createCipheriv("aes-256-gcm", key, iv)
  const plaintext = Buffer.from(JSON.stringify(payload), "utf8")
  const ciphertext = Buffer.concat([cipher.update(plaintext), cipher.final()])
  const tag = cipher.getAuthTag()
  return Buffer.from(
    `${JSON.stringify(
      {
        schemaVersion: 1,
        encryption: "aes-256-gcm",
        keyDerivation: "pbkdf2-sha512",
        iterations: 600_000,
        salt: salt.toString("base64"),
        iv: iv.toString("base64"),
        tag: tag.toString("base64"),
        ciphertext: ciphertext.toString("base64"),
      },
      null,
      2,
    )}\n`,
    "utf8",
  )
}

function writeEnvironmentFile(values) {
  const content = [
    "# Generated by pnpm mobile:keys:init. This file is intentionally gitignored.",
    `ANYBOX_ANDROID_KEYSTORE_PATH=${values.keystorePath}`,
    `ANYBOX_ANDROID_KEYSTORE_PASSWORD=${values.storePassword}`,
    `ANYBOX_ANDROID_KEY_ALIAS=${values.keyAlias}`,
    `ANYBOX_ANDROID_KEY_PASSWORD=${values.keyPassword}`,
    `ANYBOX_OTA_PRIVATE_KEY_PATH=${values.otaPrivateKeyPath}`,
    `ANYBOX_OTA_CERTIFICATE_PATH=${values.otaCertificatePath}`,
    "ANYBOX_OTA_KEY_ID=anybox-mobile-2026",
    "",
  ].join("\n")
  writeFileSync(envPath, content, { encoding: "utf8", mode: 0o600, flag: "wx" })
}

function assertGitProtection() {
  const protectedPaths = [
    {
      label: privateRoot,
      probe: path.join(privateRoot, "__anybox_gitignore_probe__"),
    },
    { label: envPath, probe: envPath },
  ]
  for (const protectedPath of protectedPaths) {
    const ignored = spawnSync("git", ["check-ignore", "-q", "--", protectedPath.probe], {
      cwd: repoRoot,
      windowsHide: true,
    })
    if (ignored.status !== 0) {
      throw new Error(`Private key path is not protected by .gitignore: ${protectedPath.label}`)
    }
  }
}

function main() {
  const args = parseArgs(process.argv.slice(2))
  if (args.help) {
    console.log(usage())
    return
  }

  if (!path.isAbsolute(args.primaryBackup) || !path.isAbsolute(args.secondaryBackup)) {
    throw new Error("Both backup destinations must be absolute directory paths.\n\n" + usage())
  }
  const primaryDirectory = path.resolve(args.primaryBackup)
  const secondaryDirectory = path.resolve(args.secondaryBackup)
  if (primaryDirectory.toLowerCase() === secondaryDirectory.toLowerCase()) {
    throw new Error("Primary and secondary backup directories must be different.")
  }
  if (isInside(repoRoot, primaryDirectory) || isInside(repoRoot, secondaryDirectory)) {
    throw new Error("Encrypted backup directories must be outside the Anybox Git repository.")
  }
  const passphrase = process.env.ANYBOX_MOBILE_BACKUP_PASSPHRASE ?? ""
  if (passphrase.length < 16) {
    throw new Error("ANYBOX_MOBILE_BACKUP_PASSPHRASE must contain at least 16 characters.")
  }

  const primaryBackupPath = path.join(primaryDirectory, backupFileName)
  const secondaryBackupPath = path.join(secondaryDirectory, backupFileName)
  for (const [filePath, label] of [
    [keystorePath, "Android keystore"],
    [otaPrivateKeyPath, "OTA private key"],
    [otaPublicKeyPath, "OTA public key"],
    [generatedCertificatePath, "generated OTA certificate"],
    [committedCertificatePath, "committed OTA certificate"],
    [committedAndroidFingerprintPath, "committed Android certificate fingerprint"],
    [envPath, "local signing environment"],
    [primaryBackupPath, "primary encrypted backup"],
    [secondaryBackupPath, "secondary encrypted backup"],
  ]) {
    requireFreshPath(filePath, label)
  }
  assertGitProtection()

  mkdirSync(androidKeyDirectory, { recursive: true })
  mkdirSync(otaKeyDirectory, { recursive: true })
  mkdirSync(temporaryCertificateDirectory, { recursive: true })
  mkdirSync(primaryDirectory, { recursive: true })
  mkdirSync(secondaryDirectory, { recursive: true })

  const storePassword = randomPassword()
  const keyPassword = randomPassword()
  const keytoolEnvironment = {
    ...process.env,
    ANYBOX_MOBILE_INIT_STORE_PASSWORD: storePassword,
    ANYBOX_MOBILE_INIT_KEY_PASSWORD: keyPassword,
  }
  run("keytool", [
    "-genkeypair",
    "-v",
    "-storetype",
    "JKS",
    "-keystore",
    keystorePath,
    "-storepass:env",
    "ANYBOX_MOBILE_INIT_STORE_PASSWORD",
    "-keypass:env",
    "ANYBOX_MOBILE_INIT_KEY_PASSWORD",
    "-alias",
    androidAlias,
    "-keyalg",
    "RSA",
    "-keysize",
    "4096",
    "-sigalg",
    "SHA256withRSA",
    "-validity",
    "10000",
    "-dname",
    "CN=Anybox Mobile, OU=Release, O=Anybox, L=Shenzhen, ST=Guangdong, C=CN",
  ], { env: keytoolEnvironment })

  const expoUpdates = path.join(packageRoot, "node_modules", "expo-updates", "bin", "cli.js")
  if (!existsSync(expoUpdates)) throw new Error("expo-updates CLI is unavailable. Run corepack pnpm install first.")
  run(
    process.execPath,
    [
      expoUpdates,
      "codesigning:generate",
      "--key-output-directory",
      otaKeyDirectory,
      "--certificate-output-directory",
      temporaryCertificateDirectory,
      "--certificate-validity-duration-years",
      "30",
      "--certificate-common-name",
      "Anybox Mobile OTA 2026",
    ],
  )
  copyFileSync(generatedCertificatePath, committedCertificatePath, COPYFILE_EXCL)

  const environment = {
    keystorePath,
    storePassword,
    keyAlias: androidAlias,
    keyPassword,
    otaPrivateKeyPath,
    otaCertificatePath: committedCertificatePath,
  }
  writeEnvironmentFile(environment)

  const backupPayload = {
    schemaVersion: 1,
    generatedAt: new Date().toISOString(),
    keyId: "anybox-mobile-2026",
    android: {
      alias: androidAlias,
      storePassword,
      keyPassword,
      keystoreBase64: readFileSync(keystorePath).toString("base64"),
    },
    ota: {
      privateKeyPem: readFileSync(otaPrivateKeyPath, "utf8"),
      publicKeyPem: readFileSync(otaPublicKeyPath, "utf8"),
      certificatePem: readFileSync(committedCertificatePath, "utf8"),
    },
  }
  const encryptedBackup = createEncryptedBackup(backupPayload, passphrase)
  writeFileSync(primaryBackupPath, encryptedBackup, { flag: "wx", mode: 0o600 })
  writeFileSync(secondaryBackupPath, encryptedBackup, { flag: "wx", mode: 0o600 })

  const backupSha256 = createHash("sha256").update(encryptedBackup).digest("hex")
  const otaCertificate = new X509Certificate(readFileSync(committedCertificatePath))
  const keytoolOutput = run(
    "keytool",
    [
      "-list",
      "-v",
      "-keystore",
      keystorePath,
      "-storepass:env",
      "ANYBOX_MOBILE_INIT_STORE_PASSWORD",
      "-alias",
      androidAlias,
    ],
    { capture: true, env: keytoolEnvironment },
  )
  const androidCertificate = keytoolOutput.match(/SHA256:\s*([A-Fa-f0-9:]+)/i)?.[1] ?? "unavailable"
  const normalizedAndroidCertificate = androidCertificate
    .replaceAll(":", "")
    .trim()
    .toLowerCase()
  if (!/^[a-f0-9]{64}$/.test(normalizedAndroidCertificate)) {
    throw new Error("Unable to read the generated Android release certificate fingerprint.")
  }
  writeFileSync(committedAndroidFingerprintPath, `${normalizedAndroidCertificate}\n`, {
    encoding: "utf8",
    flag: "wx",
  })

  console.log("Anybox mobile production keys were initialized.")
  console.log(`Public OTA certificate: ${committedCertificatePath}`)
  console.log(`Android certificate SHA-256: ${normalizedAndroidCertificate}`)
  console.log(`OTA certificate SHA-256: ${otaCertificate.fingerprint256}`)
  console.log(`Encrypted backup SHA-256: ${backupSha256}`)
  console.log(`Primary backup: ${primaryBackupPath}`)
  console.log(`Secondary backup: ${secondaryBackupPath}`)
  console.log("Store the backup passphrase separately. It is not written to disk by this command.")
}

const { COPYFILE_EXCL } = await import("node:constants")

try {
  main()
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error))
  process.exit(1)
}
