export type MobileTranslationKey = keyof typeof zhCN

export const translations: Record<MobileLocale, Record<MobileTranslationKey, string>> = {
  "zh-CN": zhCN,
  "en-US": enUS,
}

export function isMobileLocale(value: string): value is MobileLocale {
  return MOBILE_LOCALES.includes(value as MobileLocale)
}

export function normalizeMobileLocale(value: unknown): MobileLocale | null {
  return typeof value === "string" && isMobileLocale(value) ? value : null
}
