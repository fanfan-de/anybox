const { withAppBuildGradle } = require("expo/config-plugins")

const SIGNING_CONFIG_MARKER = "// @generated by with-android-release-signing"

function addReleaseSigningConfig(source) {
  if (source.includes(SIGNING_CONFIG_MARKER)) return source

  const signingConfigBlock = `    ${SIGNING_CONFIG_MARKER}
    def anyboxReleaseStoreFile = System.getenv("ANYBOX_ANDROID_KEYSTORE_PATH")
    def anyboxReleaseStorePassword = System.getenv("ANYBOX_ANDROID_KEYSTORE_PASSWORD")
    def anyboxReleaseKeyAlias = System.getenv("ANYBOX_ANDROID_KEY_ALIAS")
    def anyboxReleaseKeyPassword = System.getenv("ANYBOX_ANDROID_KEY_PASSWORD")

`
  const withVariables = source.replace(/(\nandroid\s*\{\s*\n)/, `$1${signingConfigBlock}`)
  if (withVariables === source) {
    throw new Error("Unable to locate the Android Gradle block for Anybox release signing.")
  }

  const debugSigningConfig = /(\s+signingConfigs\s*\{\s*\n\s+debug\s*\{[\s\S]*?\n\s+\}\s*\n)(\s+\})/
  const withReleaseConfig = withVariables.replace(
    debugSigningConfig,
    `$1        release {
            if (anyboxReleaseStoreFile) {
                storeFile file(anyboxReleaseStoreFile)
                storePassword anyboxReleaseStorePassword
                keyAlias anyboxReleaseKeyAlias
                keyPassword anyboxReleaseKeyPassword
            }
        }
$2`,
  )
  if (withReleaseConfig === withVariables) {
    throw new Error("Unable to locate signingConfigs.debug in Android app/build.gradle.")
  }

  const withReleaseBuild = withReleaseConfig.replace(
    /(buildTypes\s*\{[\s\S]*?\n\s+release\s*\{[\s\S]*?\n)(\s+)signingConfig signingConfigs\.debug/,
    "$1$2signingConfig signingConfigs.release",
  )
  if (withReleaseBuild === withReleaseConfig) {
    throw new Error("Unable to replace the debug signing config used by the Android release build.")
  }
  return withReleaseBuild
}

module.exports = function withAndroidReleaseSigning(config) {
  return withAppBuildGradle(config, (gradleConfig) => {
    if (gradleConfig.modResults.language !== "groovy") {
      throw new Error("Anybox Android release signing currently expects a Groovy app/build.gradle.")
    }
    gradleConfig.modResults.contents = addReleaseSigningConfig(gradleConfig.modResults.contents)
    return gradleConfig
  })
}

module.exports.addReleaseSigningConfig = addReleaseSigningConfig
