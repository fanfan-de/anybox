function normalizeGenerationLabel(value: string): string {
  return value.trim().toLowerCase().replace(/[^a-z0-9]+/g, "")
}

export function translateGenerationParameterLabel(locale: Locale, key: string, fallbackLabel: string): string {
  const translationKey = generationParameterTranslationKeys[normalizeGenerationLabel(key)]
    ?? generationParameterTranslationKeys[normalizeGenerationLabel(fallbackLabel)]
  return translationKey ? translate(locale, translationKey) : fallbackLabel
}

